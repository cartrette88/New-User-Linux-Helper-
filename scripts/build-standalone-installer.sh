#!/usr/bin/env bash
# Build command-helper-installer.sh from the individual project files.
# SPDX-License-Identifier: MIT
if [ -z "${BASH_VERSION:-}" ]; then
  echo "Run this with bash." >&2
  exit 1
fi
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
out=${1:-"${root}/command-helper-installer.sh"}

pin() {
  local key=$1 line
  line=$(grep -E "^${key}=" "${root}/install.sh" | head -n 1)
  line=${line#*=}
  line=${line#\"}
  line=${line%\"}
  if [[ -z $line ]]; then
    printf 'Missing %s in install.sh\n' "$key" >&2
    exit 1
  fi
  printf '%s' "$line"
}

llama_version=$(pin LLAMA_VERSION)
llama_commit=$(pin LLAMA_COMMIT)
model_file=$(pin MODEL_FILE)
model_revision=$(pin MODEL_REVISION)
sha_cpu_x64=$(pin SHA_CPU_X64)
sha_cpu_arm64=$(pin SHA_CPU_ARM64)
sha_cuda_x64=$(pin SHA_CUDA_X64)
sha_cudart_x64=$(pin SHA_CUDART_X64)
model_sha=$(pin MODEL_SHA256)

files=(
  "install.sh|END_COMMAND_HELPER_FILE_INSTALL"
  "uninstall.sh|END_COMMAND_HELPER_FILE_UNINSTALL"
  "bin/ask|END_COMMAND_HELPER_FILE_ASK"
  "bin/command-helper-launch|END_COMMAND_HELPER_FILE_LAUNCH"
  "share/command-helper.desktop|END_COMMAND_HELPER_FILE_DESKTOP"
)

entry=""
src=""
marker=""
for entry in "${files[@]}"; do
  src=${entry%%|*}
  marker=${entry#*|}
  if [[ ! -f ${root}/${src} ]]; then
    printf 'Missing %s\n' "$src" >&2
    exit 1
  fi
  if [[ $(tail -c 1 "${root}/${src}" | wc -l) -eq 0 ]]; then
    printf '%s must end with a newline.\n' "$src" >&2
    exit 1
  fi
  if grep -qF "$marker" "${root}/${src}"; then
    printf 'Marker %s appears inside %s.\n' "$marker" "$src" >&2
    exit 1
  fi
done

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  cat <<EOF
#!/usr/bin/env bash
# Command Helper — single-file installer
# Generated by scripts/build-standalone-installer.sh. Edit the source files, then regenerate.
#
# This installs a local, offline command helper for the current Linux user.
# It does not use sudo, and it does not send what you type to a cloud service.
#
# Read this file before you run it. The program files are written out in plain
# text below. The same files are also published separately in the project
# repository: install.sh, uninstall.sh, bin/ask, bin/command-helper-launch,
# and share/command-helper.desktop.
#
# A normal install downloads:
#   llama.cpp ${llama_version} (commit ${llama_commit}) CPU build
#   ${model_file}
#     Hugging Face revision ${model_revision}
# Pass --cuda only for an NVIDIA graphics card on 64-bit Intel/AMD.
# That option also downloads the CUDA runtime libraries published with llama.cpp.
#
# Pinned fingerprints (SHA256):
#   llama.cpp CPU x86_64:  ${sha_cpu_x64}
#   llama.cpp CPU arm64:   ${sha_cpu_arm64}
#   llama.cpp CUDA 12.8 x86_64 (only with --cuda): ${sha_cuda_x64}
#   CUDA runtime libraries (only with --cuda): ${sha_cudart_x64}
#   model: ${model_sha}
#
# Run:   bash command-helper-installer.sh
# Help:  bash command-helper-installer.sh --help
EOF
  cat <<'EOF'

if [ -z "${BASH_VERSION:-}" ]; then
  echo "Please run this installer with bash:  bash command-helper-installer.sh" >&2
  exit 1
fi
set -euo pipefail

if [ "${EUID:-$(id -u)}" -eq 0 ]; then
  printf '%s\n' "Please run this installer as your normal user, without sudo." >&2
  exit 1
fi

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT
mkdir -p "${tmpdir}/bin" "${tmpdir}/share"
EOF

  local_mode=""
  for entry in "${files[@]}"; do
    src=${entry%%|*}
    marker=${entry#*|}
    local_mode=755
    if [[ $src == *.desktop ]]; then
      local_mode=644
    fi
    printf '\n# --- %s ---\n' "$src"
    # The generated installer expands $tmpdir when it runs, not while building.
    # shellcheck disable=SC2016
    printf 'cat > "$tmpdir/%s" <<'\''%s'\''\n' "$src" "$marker"
    cat "${root}/${src}"
    printf '%s\n' "$marker"
    # shellcheck disable=SC2016
    printf 'chmod %s "$tmpdir/%s"\n' "$local_mode" "$src"
  done

  # shellcheck disable=SC2016
  printf '\nbash "$tmpdir/install.sh" "$@"\n'
} > "$tmp"

bash -n "$tmp"
mv -f "$tmp" "$out"
chmod 755 "$out"
trap - EXIT
printf 'Wrote %s\n' "$out"
