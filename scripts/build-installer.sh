#!/usr/bin/env bash
# Rebuild install.sh and command-helper-installer.sh from scripts/common.sh
# and the program files. Run this after changing those sources.
set -euo pipefail

if [ -z "${BASH_VERSION:-}" ]; then
  printf 'Run this script with bash.\n' >&2
  exit 1
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMMON="${ROOT}/scripts/common.sh"

emit_common() {
  sed '/^#!\/usr\/bin\/env bash$/d' "$COMMON"
}

embed_file() {
  local dest_rel=$1 src=$2 marker=$3 mode=$4
  if grep -q "$marker" "$src"; then
    printf 'Refusing to embed %s: it already contains the marker %s\n' "$src" "$marker" >&2
    exit 1
  fi
  # $dest is expanded when the generated installer runs, not here.
  # shellcheck disable=SC2016
  printf '  mkdir -p "$(dirname "$dest/%s")"\n' "$dest_rel"
  printf "  cat > \"\$dest/%s\" << '%s'\n" "$dest_rel" "$marker"
  cat "$src"
  if [ -n "$(tail -c 1 "$src")" ]; then
    printf '\n'
  fi
  printf '%s\n' "$marker"
  # shellcheck disable=SC2016
  printf '  chmod %s "$dest/%s"\n' "$mode" "$dest_rel"
}

write_install_sh() {
  local out="${ROOT}/install.sh"
  {
    cat << 'EOF'
#!/usr/bin/env bash
# Install Command Helper from a copy of this project.
# Generated by scripts/build-installer.sh. Do not edit by hand.
# For a single download, use command-helper-installer.sh instead.
EOF
    cat << 'EOF'
if [ -z "${BASH_VERSION:-}" ]; then
  printf 'Run this script with bash.\n' >&2
  exit 1
fi
set -euo pipefail

EOF
    emit_common
    cat << 'EOF'

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ch_dispatch "$ROOT" "$@"
EOF
  } > "$out"
  chmod 755 "$out"
}

write_self_contained() {
  local out="${ROOT}/command-helper-installer.sh"
  {
    cat << 'EOF'
#!/usr/bin/env bash
# Command Helper — self-contained installer.
# Generated by scripts/build-installer.sh. Do not edit by hand.
#
# Read this file before you run it. It does not use sudo.
# It installs Command Helper for the current user under ~/.local, then
# downloads the pinned llama.cpp CPU build from GitHub and the pinned
# Qwen3 model from Hugging Face. Both downloads are checked with SHA256.
#
# The program files are embedded further down so this one file is enough.
EOF
    cat << 'EOF'
if [ -z "${BASH_VERSION:-}" ]; then
  printf 'Run this script with bash.\n' >&2
  exit 1
fi
set -euo pipefail

EOF
    emit_common
    cat << 'EOF'

# Program files embedded so this installer is a single download.
ch_extract_payloads() {
  local dest=$1
EOF
    embed_file "bin/ask" "${ROOT}/bin/ask" "CH_EMBED_ASK" 755
    embed_file "bin/command-helper-launch" "${ROOT}/bin/command-helper-launch" "CH_EMBED_LAUNCH" 755
    embed_file "share/command-helper.desktop" "${ROOT}/share/command-helper.desktop" "CH_EMBED_DESKTOP" 644
    embed_file "uninstall.sh" "${ROOT}/uninstall.sh" "CH_EMBED_UNINSTALL" 755
    cat << 'EOF'
}

case "${1:-}" in
  -h|--help)
    ch_print_help
    exit 0
    ;;
  -V|--version)
    printf '%s\n' "$CH_VERSION"
    exit 0
    ;;
  "")
    ;;
  *)
    printf 'ERROR: Unknown option: %s (try --help)\n' "$1" >&2
    exit 1
    ;;
esac

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
ch_extract_payloads "$tmp"
ch_dispatch "$tmp"
EOF
  } > "$out"
  chmod 755 "$out"
}

write_install_sh
write_self_contained
printf 'Wrote %s and %s\n' "${ROOT}/install.sh" "${ROOT}/command-helper-installer.sh"
